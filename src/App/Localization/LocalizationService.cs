    public static string CurrentLanguage { get; private set; } = DefaultLanguage;
    public static IReadOnlyList<InterfaceLanguageOption> Languages { get; } =
    [
        new("ru-RU", "Русский"),
        new("en-US", "English")
    ];

    public static void Initialize()
    {
        string? saved = null;
        try
        {
            if (File.Exists(PreferencePath)) saved = File.ReadAllText(PreferencePath).Trim();
        }
        catch
        {
            // A missing or unreadable preference must never prevent startup.
        }
        CurrentLanguage = NormalizeLanguage(saved);
        var culture = CultureInfo.GetCultureInfo(CurrentLanguage);
        CultureInfo.DefaultThreadCurrentCulture = culture;
        CultureInfo.DefaultThreadCurrentUICulture = culture;
        CultureInfo.CurrentCulture = culture;
        CultureInfo.CurrentUICulture = culture;
    }

    public static string Get(string key) => CurrentLanguage.StartsWith("ru", StringComparison.OrdinalIgnoreCase) && Russian.TryGetValue(key, out var value) ? value : key;
    public static string Format(string key, params object?[] args) => string.Format(CultureInfo.CurrentCulture, Get(key), args);

    public static string NormalizeLanguage(string? value) => value?.StartsWith("en", StringComparison.OrdinalIgnoreCase) == true ? "en-US" : DefaultLanguage;

    public static void SavePreference(string? language)
    {
        var normalized = NormalizeLanguage(language);
        try
        {
            Directory.CreateDirectory(Path.GetDirectoryName(PreferencePath)!);
            File.WriteAllText(PreferencePath, normalized);
        }
        catch
        {
            // The database preference is still saved by SettingsViewModel.
        }
    }

    public static void RestartApplication()
    {
#if ANDROID
        Initialize();
        var frame = new Microsoft.UI.Xaml.Controls.Frame();
        App.Window.Content = frame;
        frame.Navigate(typeof(MainPage));
#else
        var executable = Environment.ProcessPath;
        if (string.IsNullOrWhiteSpace(executable)) return;
        Process.Start(new ProcessStartInfo(executable) { UseShellExecute = true, WorkingDirectory = AppContext.BaseDirectory });
        App.Window.Close();
#endif
    }
}

